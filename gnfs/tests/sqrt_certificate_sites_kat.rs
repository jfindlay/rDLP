//! Who may mint the square-root outcome witnesses, checked against the source tree.
//!
//! A `VerifiedRoot` certifies that `β² = γ` held exactly and that the modular image was computed,
//! so it may be built in exactly one place, after the exact verifier has accepted a candidate:
//! `VerifiedRoot::seal`, which the compiler confines to the `sqrt::context` module subtree. A
//! `NonSquareCertificate` certifies that no root exists, which is only established by a local
//! obstruction or a complete bounded search. Its constructor is visible to the whole `sqrt`
//! module, so the compiler does not confine it; this test does, by pinning the production call
//! sites.
//!
//! The scan reads `src/` as text. Comments, string and character literals, and `#[cfg(test)]`
//! items are removed first, so only production code counts, and calls are matched by file and
//! number of sites, never by line. Adding, moving between files, or removing a minting site fails
//! the test and needs a deliberate update to the expected tables below: a new site is a new place
//! that must justify a non-square verdict. The scan cannot see a call made through a `use … as`
//! alias or generated by a macro; neither is used for these items.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

/// Production call sites of `NonSquareCertificate::new`: the exact-reconstruction paths that can
/// prove a nonsquare, by file relative to `src/` and number of calls. `sqrt/padic.rs` certifies
/// from a nonresidue in the residue field and from the rejection of the lifted candidate at a
/// modulus above twice the proved bound; `sqrt/crt.rs` from a nonresidue at a root of a split
/// prime and from exhaustion of the complete sign search.
const CERTIFICATE_SITES: [(&str, usize); 2] = [("sqrt/crt.rs", 2), ("sqrt/padic.rs", 2)];

/// Production call sites of `VerifiedRoot::seal`: the single acceptance of a verified candidate.
const SEAL_SITES: [(&str, usize); 1] = [("sqrt/context/normalize.rs", 1)];

const CERTIFICATE_CALL: &str = "NonSquareCertificate::new(";
const SEAL_CALL: &str = "VerifiedRoot::seal(";

// ─── scanning ────────────────────────────────────────────────────────────────

/// `source` with comments removed and string and character literal contents blanked, so that
/// neither can hide or fake a call. Braces and parentheses in the result are all real code.
fn blank_comments_and_literals(source: &str) -> String {
    let chars: Vec<char> = source.chars().collect();
    let mut out = String::with_capacity(source.len());
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        let next = chars.get(i + 1).copied();
        if c == '/' && next == Some('/') {
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
        } else if c == '/' && next == Some('*') {
            i = skip_block_comment(&chars, i);
            out.push(' ');
        } else if let Some(end) = raw_string_end(&chars, i) {
            i = end;
            out.push_str("\"\"");
        } else if c == '"' {
            i = skip_string(&chars, i);
            out.push_str("\"\"");
        } else if c == '\'' {
            if let Some(end) = char_literal_end(&chars, i) {
                i = end;
                out.push_str("''");
            } else {
                // A lifetime or label, which has no closing quote.
                out.push(c);
                i += 1;
            }
        } else {
            out.push(c);
            i += 1;
        }
    }
    out
}

/// Index just past the (possibly nested) block comment starting at `start`.
fn skip_block_comment(chars: &[char], start: usize) -> usize {
    let (mut i, mut depth) = (start, 0usize);
    while i < chars.len() {
        if chars[i] == '/' && chars.get(i + 1) == Some(&'*') {
            depth += 1;
            i += 2;
        } else if chars[i] == '*' && chars.get(i + 1) == Some(&'/') {
            depth -= 1;
            i += 2;
            if depth == 0 {
                break;
            }
        } else {
            i += 1;
        }
    }
    i
}

/// Index just past the ordinary string literal whose opening quote is at `start`.
fn skip_string(chars: &[char], start: usize) -> usize {
    let mut i = start + 1;
    while i < chars.len() {
        match chars[i] {
            '\\' => i += 2,
            '"' => return i + 1,
            _ => i += 1,
        }
    }
    i
}

/// If a raw string literal (`r"…"`, `r#"…"#`, optionally with a `b` prefix) starts at `start`,
/// the index just past it.
fn raw_string_end(chars: &[char], start: usize) -> Option<usize> {
    let after_prefix = match (chars[start], chars.get(start + 1)) {
        ('r', _) => start + 1,
        ('b', Some('r')) => start + 2,
        _ => return None,
    };
    let preceded_by_identifier =
        start > 0 && (chars[start - 1].is_alphanumeric() || chars[start - 1] == '_');
    if preceded_by_identifier {
        return None;
    }
    let hashes = chars[after_prefix..].iter().take_while(|&&c| c == '#').count();
    if chars.get(after_prefix + hashes) != Some(&'"') {
        return None;
    }
    let closing: Vec<char> = std::iter::once('"').chain(std::iter::repeat_n('#', hashes)).collect();
    let body = after_prefix + hashes + 1;
    let found = (body..chars.len()).find(|&j| chars[j..].starts_with(&closing))?;
    Some(found + closing.len())
}

/// If a character literal starts at `start`, the index just past it; `None` for a lifetime.
fn char_literal_end(chars: &[char], start: usize) -> Option<usize> {
    if chars.get(start + 1) == Some(&'\\') {
        // `'\n'`, `'\''`, `'\x41'`, `'\u{1F600}'`: skip the escaped character, then find the quote.
        let from = start + 3;
        let close = (from..chars.len()).find(|&j| chars[j] == '\'')?;
        return Some(close + 1);
    }
    (chars.get(start + 2) == Some(&'\'')).then_some(start + 3)
}

/// `pattern` matched at `chars[at..]` while ignoring whitespace in `chars`; the index just past
/// the match.
fn match_ignoring_whitespace(chars: &[char], at: usize, pattern: &str) -> Option<usize> {
    let mut i = at;
    for expected in pattern.chars() {
        while chars.get(i).is_some_and(|c| c.is_whitespace()) {
            i += 1;
        }
        if chars.get(i) != Some(&expected) {
            return None;
        }
        i += 1;
    }
    Some(i)
}

/// `code` without the items marked `#[cfg(test)]`: from the attribute through the closing brace
/// of the item's body, or through its terminating semicolon when it has no body.
fn strip_test_items(code: &str) -> String {
    let chars: Vec<char> = code.chars().collect();
    let mut out = String::with_capacity(code.len());
    let mut i = 0;
    while i < chars.len() {
        if chars[i] == '#' {
            if let Some(after_attribute) = match_ignoring_whitespace(&chars, i, "#[cfg(test)]") {
                i = end_of_item(&chars, after_attribute);
                continue;
            }
        }
        out.push(chars[i]);
        i += 1;
    }
    out
}

/// Index just past the item whose attributes end at `start`. Brackets and parentheses are
/// skipped as a unit, so a `;` in an array type or a `{` in a signature does not end the item.
fn end_of_item(chars: &[char], start: usize) -> usize {
    let mut i = start;
    let mut nesting = 0usize;
    while i < chars.len() {
        match chars[i] {
            '(' | '[' => nesting += 1,
            ')' | ']' => nesting = nesting.saturating_sub(1),
            ';' if nesting == 0 => return i + 1,
            '{' if nesting == 0 => return end_of_block(chars, i),
            _ => {}
        }
        i += 1;
    }
    i
}

/// Index just past the brace block opened at `open`.
fn end_of_block(chars: &[char], open: usize) -> usize {
    let mut depth = 0usize;
    for (offset, &c) in chars[open..].iter().enumerate() {
        match c {
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if depth == 0 {
                    return open + offset + 1;
                }
            }
            _ => {}
        }
    }
    chars.len()
}

/// The number of production calls of `call` (for example `Type::function(`) in `source`.
///
/// A match is rejected when it continues a longer identifier on the left, so `MyType::function(`
/// is not `Type::function(`.
fn production_calls(source: &str, call: &str) -> usize {
    let code = strip_test_items(&blank_comments_and_literals(source));
    let chars: Vec<char> = code.chars().collect();
    let first = call.chars().next().expect("call is not empty");
    (0..chars.len())
        .filter(|&at| {
            // Anchor on the first character so that leading whitespace cannot match twice.
            let continues_identifier =
                at > 0 && (chars[at - 1].is_alphanumeric() || chars[at - 1] == '_');
            chars[at] == first
                && !continues_identifier
                && match_ignoring_whitespace(&chars, at, call).is_some()
        })
        .count()
}

/// Every `.rs` file under `dir`, recursively.
fn rust_files(dir: &Path, found: &mut Vec<PathBuf>) {
    let mut entries: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .map(|entry| entry.expect("directory entry is readable").path())
        .collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            rust_files(&path, found);
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            found.push(path);
        }
    }
}

/// The files of `gnfs/src` that contain production calls of `call`, with the number of calls,
/// keyed by path relative to `src/` with `/` separators.
fn sites_of(call: &str) -> BTreeMap<String, usize> {
    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let mut files = Vec::new();
    rust_files(&src, &mut files);
    // A moved or renamed tree must fail loudly rather than pass because nothing was scanned.
    for required in ["sqrt/padic.rs", "sqrt/crt.rs", "sqrt/context.rs", "sqrt/context/normalize.rs"]
    {
        assert!(
            files.iter().any(|f| f.ends_with(required)),
            "expected source file {required} under {}",
            src.display()
        );
    }
    files
        .iter()
        .filter_map(|path| {
            let text = fs::read_to_string(path)
                .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
            let count = production_calls(&text, call);
            let relative = path.strip_prefix(&src).expect("path is under src");
            let key = relative.to_string_lossy().replace('\\', "/");
            (count > 0).then_some((key, count))
        })
        .collect()
}

fn expected(table: &[(&str, usize)]) -> BTreeMap<String, usize> {
    table.iter().map(|&(file, count)| (file.to_string(), count)).collect()
}

// ─── the rules ───────────────────────────────────────────────────────────────

/// A nonsquare verdict is minted only by the two exact reconstruction paths.
#[test]
fn kat_nonsquare_certificates_are_minted_only_by_exact_reconstruction() {
    assert_eq!(sites_of(CERTIFICATE_CALL), expected(&CERTIFICATE_SITES));
}

/// A verified root is sealed only by the exact verifier of the normalized target. The definition
/// in `sqrt/context.rs` and the call in its own test module are not production call sites.
#[test]
fn kat_verified_roots_are_sealed_only_by_the_exact_verifier() {
    assert_eq!(sites_of(SEAL_CALL), expected(&SEAL_SITES));
}

// ─── the scanner itself ──────────────────────────────────────────────────────

/// Only code outside comments, literals, and `#[cfg(test)]` items counts, so the pinned tables
/// above cannot be satisfied or evaded by text that is not a call.
#[test]
fn kat_scanner_counts_only_production_calls() {
    let call = "Cert::new(";
    let production = "fn f() { let _ = Cert::new(1); }";
    assert_eq!(production_calls(production, call), 1);

    // Whitespace and line breaks inside the path and before the parenthesis do not hide a call.
    assert_eq!(production_calls("fn f() { Cert\n    ::new\n    (1); }", call), 1);
    // A longer identifier on the left is a different item.
    assert_eq!(production_calls("fn f() { MyCert::new(1); }", call), 0);
    // A definition is not a call.
    assert_eq!(production_calls("impl Cert { fn new(x: u8) -> Self { Self } }", call), 0);

    // Text that is not code does not count.
    assert_eq!(production_calls("// Cert::new(1)\n/// Cert::new(1)\nfn f() {}", call), 0);
    assert_eq!(production_calls("/* Cert::new(1) /* nested Cert::new(1) */ Cert::new(1) */", call), 0);
    assert_eq!(production_calls("fn f() { let s = \"Cert::new(1) \\\" Cert::new(1)\"; }", call), 0);
    assert_eq!(production_calls("fn f() { let s = r#\"Cert::new(1) \" Cert::new(1)\"#; }", call), 0);
    // A quote character does not open a string that would swallow a real call after it.
    assert_eq!(production_calls("fn f<'a>(x: &'a str) { let _ = ('\"', Cert::new(1)); }", call), 1);

    // Test-only items do not count: a module, a function whose signature contains `;` and `{`
    // inside brackets, and a body-less item. A call after them still does.
    let test_module = "#[cfg(test)]\nmod tests { fn t() { Cert::new(1); } }\nfn f() { Cert::new(2); }";
    assert_eq!(production_calls(test_module, call), 1);
    let test_function = "#[cfg(test)]\nfn t(x: [u8; 4]) { Cert::new(1); }\nfn f() { Cert::new(2); }";
    assert_eq!(production_calls(test_function, call), 1);
    let test_use = "#[cfg(test)]\nuse crate::x;\nfn f() { Cert::new(2); }";
    assert_eq!(production_calls(test_use, call), 1);
    let not_test = "#[cfg(not(test))]\nfn f() { Cert::new(1); }";
    assert_eq!(production_calls(not_test, call), 1);
}
