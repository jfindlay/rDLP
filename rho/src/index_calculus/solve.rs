//! DLP recovery for the index-calculus ECDLP solver: the full pipeline assembler.
//!
//! This module assembles the index-calculus pipeline and recovers `log_G(Q) mod ℓ` from a
//! combination of collected relations.
//!
//! # Pipeline
//!
//! 1. **Relation collection** ([`RelationStream`]) — enumerate `a·G + b·Q` multiples,
//!    decompose each over the factor base (via Semaev `decompose`), and record every
//!    success as a `Relation` row.
//! 2. **Linear algebra** (`solve_ek_linalg`) — compute a basis of the left kernel of the
//!    relation exponent matrix over `F_ℓ`: the combinations `u` with `Σᵢ uᵢ·eᵢ ≡ 0`.
//! 3. **Recovery** (this module) — turn a combination `u` into `x = log_G(Q) mod ℓ`.
//!
//! # Why the logarithms live mod ℓ
//!
//! The group has order `n` and `ℓ` divides `n` exactly once. Its `ℓ`-Sylow subgroup is
//! therefore cyclic of order `ℓ`, generated by `G_ℓ = (n/ℓ)·G`. Multiplying any point by
//! `n/ℓ` projects it into that subgroup, so the `ℓ`-component of every factor-base point
//! `P_j` and of `Q` lies in `⟨G_ℓ⟩` and has a logarithm modulo `ℓ`.
//!
//! # Recovery derivation
//!
//! Each relation `i` records `a_i·G + b_i·Q = Σ_j e_ij·P_j`. Projecting to the
//! `ℓ`-component and taking logarithms to the base `G_ℓ` gives, with `x = log_G(Q) mod ℓ`
//! and `l_j = log_{G_ℓ}((n/ℓ)·P_j)`,
//!
//! ```text
//! a_i + b_i·x ≡ Σ_j e_ij·l_j   (mod ℓ).
//! ```
//!
//! A kernel combination `u` satisfies `Σ_i u_i·e_ij ≡ 0` for every `j`, so summing the
//! relations weighted by `u` cancels every unknown `l_j`:
//!
//! ```text
//! uᵀa + (uᵀb)·x ≡ 0   (mod ℓ).
//! ```
//!
//! When `uᵀb ≢ 0` this gives `x ≡ −uᵀa / uᵀb`. When `uᵀb ≡ 0` the combination says nothing
//! about `x`, and honest relations force `uᵀa ≡ 0`. The value of `x` therefore comes only
//! from a relation combination, never from trying candidate logarithms.
//!
//! # Outcomes
//!
//! - **Success** is verified independently of the relations: `x·G_ℓ == Q_ℓ` by the group
//!   law, and every basis vector with `uᵀb ≢ 0` must give the same `x`.
//! - **`Undetermined`** — after the full `(a, b)` enumeration, no kernel vector has
//!   `uᵀb ≢ 0`. It certifies only this relation set, because the kernel basis is complete.
//! - **`Inconsistent`** — an invariant failure (disagreeing combinations, a combination
//!   with `uᵀb ≡ 0` but `uᵀa ≢ 0`, or a failed verification). It is returned, never retried
//!   or masked.
//!
//! # Scale
//!
//! This is the index-calculus mechanism over `E(F_p)`. The asymptotic advantage over
//! Pollard rho needs the extension-field setting `E(F_{p^n})`; over `E(F_p)` at toy scale
//! index calculus is not faster.

use crypto_bigint::Uint;
use shared_field::{Fp, FpNaive4 as FpNaive};

use crate::curve::AffinePoint;
use crate::index_calculus::collect::RelationStream;
use crate::index_calculus::linalg::solve_ek_linalg;
use crate::index_calculus::strategy::{IndexCalcStrategy, Relation};
use crate::index_calculus::IndexCalcError;

// ─── IndexCalcSolution ───────────────────────────────────────────────────────

/// A verified index-calculus solution together with the evidence that produced it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct IndexCalcSolution {
    /// `log_G(Q) mod ℓ`, verified by `x·G_ℓ == Q_ℓ`.
    pub x: u64,
    /// The relation combination `u` that produced `x`: `Σᵢ uᵢ·eᵢ ≡ 0` and `uᵀb ≢ 0`.
    pub combination: Vec<FpNaive>,
    /// The relation system that `combination` combines (one entry of `u` per relation).
    pub relations: Vec<Relation>,
}

// ─── index_calculus_dlp ──────────────────────────────────────────────────────

/// Solve the ECDLP `log_G(Q) mod ℓ` using index calculus over E(F_p).
///
/// Collects relations, finds a left-kernel combination `u` with `uᵀb ≢ 0`, and recovers
/// `x ≡ −uᵀa / uᵀb (mod ℓ)`. Starts from `fb_size + 1` relations; while no basis vector
/// has `uᵀb ≢ 0`, draws a further `fb_size + 1` relations from the same deterministic
/// `(a, b)` enumeration and re-solves, until the enumeration is exhausted.
///
/// Returns the solution with the combination used and the relations it combines.
///
/// # Errors
///
/// - `UnderdeterminedSystem` if the enumeration cannot supply `fb_size + 1` relations.
/// - `Undetermined` if the whole enumeration is exhausted with no usable combination.
/// - `Inconsistent` if the relations contradict each other or verification fails.
/// - `Semaev` / `InvalidSubgroup` etc. as propagated from the earlier pipeline steps.
pub fn index_calculus_dlp(
    g: AffinePoint<FpNaive>,
    q: AffinePoint<FpNaive>,
    strategy: &IndexCalcStrategy,
) -> Result<IndexCalcSolution, IndexCalcError> {
    let batch = strategy.fb_size() + 1;
    let mut stream = RelationStream::new(g.clone(), q.clone(), strategy);
    let mut relations: Vec<Relation> = Vec::with_capacity(batch);

    if extend_relations(&mut stream, &mut relations, batch) < batch {
        return Err(IndexCalcError::UnderdeterminedSystem {
            found: relations.len(),
            needed: batch,
        });
    }

    recover_extending(relations, &mut stream, &g, &q, strategy)
}

/// Draw up to `count` further relations from `stream`; return how many were added.
fn extend_relations(
    stream: &mut RelationStream<'_>,
    relations: &mut Vec<Relation>,
    count: usize,
) -> usize {
    let mut added = 0;
    while added < count {
        match stream.next_relation() {
            Some(rel) => {
                relations.push(rel);
                added += 1;
            }
            None => break,
        }
    }
    added
}

/// Recover from `relations`, drawing more from `stream` while the outcome is `Undetermined`.
///
/// Stops with `Undetermined` once `stream` yields nothing further. Any other outcome,
/// including `Inconsistent`, is returned immediately.
fn recover_extending(
    mut relations: Vec<Relation>,
    stream: &mut RelationStream<'_>,
    g: &AffinePoint<FpNaive>,
    q: &AffinePoint<FpNaive>,
    strategy: &IndexCalcStrategy,
) -> Result<IndexCalcSolution, IndexCalcError> {
    let batch = strategy.fb_size() + 1;
    loop {
        match recover_log_from_relations(&relations, strategy, g, q) {
            Err(IndexCalcError::Undetermined { .. }) => {
                if extend_relations(stream, &mut relations, batch) == 0 {
                    return Err(IndexCalcError::Undetermined { relations: relations.len() });
                }
            }
            outcome => return outcome,
        }
    }
}

// ─── recover_log_from_relations ──────────────────────────────────────────────

/// Recover `log_G(Q) mod ℓ` from a fixed relation set via its left kernel.
///
/// Computes the complete left-kernel basis and, for each basis vector `u`, `uᵀa` and `uᵀb`
/// (with `a`, `b` reduced mod ℓ). A vector with `uᵀb ≢ 0` yields `x ≡ −uᵀa / uᵀb`; all
/// such vectors must agree, and a vector with `uᵀb ≡ 0` must have `uᵀa ≡ 0`. The first
/// vector with `uᵀb ≢ 0` is the combination reported. The agreed `x` is then verified
/// against the group law: `x·G_ℓ == Q_ℓ`.
///
/// # Errors
///
/// - `Undetermined { relations }` if no basis vector has `uᵀb ≢ 0` (including an empty
///   basis). This is about the supplied relations only; no further relations are drawn.
/// - `Inconsistent` if two combinations disagree on `x`, a combination with `uᵀb ≡ 0` has
///   `uᵀa ≢ 0`, or `x·G_ℓ ≠ Q_ℓ`.
pub fn recover_log_from_relations(
    relations: &[Relation],
    strategy: &IndexCalcStrategy,
    g: &AffinePoint<FpNaive>,
    q: &AffinePoint<FpNaive>,
) -> Result<IndexCalcSolution, IndexCalcError> {
    let ell = &strategy.ell;
    let basis = solve_ek_linalg(relations, strategy)?;

    let a: Vec<FpNaive> = relations.iter().map(|r| FpNaive::from_u64(r.a, ell)).collect();
    let b: Vec<FpNaive> = relations.iter().map(|r| FpNaive::from_u64(r.b, ell)).collect();

    let mut chosen: Option<(u64, &Vec<FpNaive>)> = None;
    for u in &basis {
        let ua = dot(u, &a, ell);
        let ub = dot(u, &b, ell);
        if ub.is_zero(ell) {
            // The combination carries no information on x, and honest relations make its
            // constant part vanish too.
            if !ua.is_zero(ell) {
                return Err(IndexCalcError::Inconsistent);
            }
            continue;
        }
        // x ≡ −uᵀa / uᵀb.
        let x = ua.neg(ell).mul(&ub.inv(ell), ell).to_uint().as_words()[0];
        match chosen {
            None => chosen = Some((x, u)),
            Some((x0, _)) if x0 != x => return Err(IndexCalcError::Inconsistent),
            Some(_) => {}
        }
    }

    let (x, u) = chosen.ok_or(IndexCalcError::Undetermined { relations: relations.len() })?;

    if !verify_log_mod_ell(x, strategy, g, q) {
        return Err(IndexCalcError::Inconsistent);
    }

    Ok(IndexCalcSolution { x, combination: u.clone(), relations: relations.to_vec() })
}

/// The inner product `Σᵢ uᵢ·vᵢ` over `F_ℓ`.
fn dot(u: &[FpNaive], v: &[FpNaive], ell: &Uint<4>) -> FpNaive {
    u.iter()
        .zip(v)
        .fold(FpNaive::zero(ell), |acc, (ui, vi)| acc.add(&ui.mul(vi, ell), ell))
}

/// Check `x·G_ℓ == Q_ℓ` with `G_ℓ = (n/ℓ)·G` and `Q_ℓ = (n/ℓ)·Q`.
fn verify_log_mod_ell(
    x: u64,
    strategy: &IndexCalcStrategy,
    g: &AffinePoint<FpNaive>,
    q: &AffinePoint<FpNaive>,
) -> bool {
    let curve = &strategy.curve;
    let cofactor = curve.n.as_words()[0] / strategy.ell.as_words()[0];
    let g_ell = curve.scalar_mul(g, &Uint::<4>::from(cofactor));
    let q_ell = curve.scalar_mul(q, &Uint::<4>::from(cofactor));
    curve.scalar_mul(&g_ell, &Uint::<4>::from(x)) == q_ell
}

// ─── unit tests ───────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;
    use crate::semaev::semaev_toy;

    fn fixture() -> (IndexCalcStrategy, AffinePoint<FpNaive>, AffinePoint<FpNaive>) {
        let strategy = IndexCalcStrategy::toy().expect("toy strategy should build");
        let curve = semaev_toy();
        let g: AffinePoint<FpNaive> = curve.generator();
        let q = curve.scalar_mul(&g, &Uint::<4>::from(7u64));
        (strategy, g, q)
    }

    /// The first `count` relations whose `b ≡ 0 (mod ℓ)`: honest, but blind to `x`.
    fn blind_relations(stream: &mut RelationStream<'_>, count: usize) -> Vec<Relation> {
        let mut out = Vec::new();
        while out.len() < count {
            let rel = stream.next_relation().expect("enough b ≡ 0 relations exist");
            if rel.b % 5 == 0 {
                out.push(rel);
            }
        }
        out
    }

    #[test]
    fn extension_supplies_a_usable_combination() {
        // Seed with relations that cannot determine x, then let the loop draw more.
        let (strategy, g, q) = fixture();
        let mut stream = RelationStream::new(g.clone(), q.clone(), &strategy);
        let seed = blind_relations(&mut stream, strategy.fb_size() + 1);
        assert_eq!(
            recover_log_from_relations(&seed, &strategy, &g, &q),
            Err(IndexCalcError::Undetermined { relations: seed.len() })
        );

        let solution = recover_extending(seed.clone(), &mut stream, &g, &q, &strategy)
            .expect("further relations determine x");
        assert_eq!(solution.x, 7 % 5);
        assert!(solution.relations.len() > seed.len(), "the relation set was extended");
        assert_eq!(solution.relations[..seed.len()], seed[..], "extension keeps the prefix");
        assert_eq!(solution.combination.len(), solution.relations.len());
    }

    #[test]
    fn exhausted_enumeration_is_undetermined() {
        let (strategy, g, q) = fixture();
        let mut stream = RelationStream::new(g.clone(), q.clone(), &strategy);
        let seed = blind_relations(&mut stream, strategy.fb_size() + 1);
        // Drain the enumeration: nothing further can be drawn.
        while stream.next_relation().is_some() {}

        assert_eq!(
            recover_extending(seed.clone(), &mut stream, &g, &q, &strategy),
            Err(IndexCalcError::Undetermined { relations: seed.len() })
        );
    }
}
