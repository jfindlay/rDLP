//! SSA reduction: multiply-by-p kernel step, F_p division, and `ssa_solve` entry point.
//!
//! This module implements the core of the Smart–Satoh–Araki reduction:
//!
//! 1. Verify the curve is anomalous.
//! 2. Lift G and Q to Z_p via Hensel ([`crate::ssa::lift::lift_point`]).
//! 3. Multiply both lifts by p using projective-coordinate point addition over Z/p^k.
//! 4. Apply log(1 + t) at t = −X/Y to both results.
//! 5. Divide in F_p to recover k.
//!
//! # Projective coordinates for multiply-by-p
//!
//! The p-th addition step in the multiply-by-p loop has a denominator divisible by p^2
//! (the affine addition formula breaks down). Standard projective coordinates `(X:Y:Z)`
//! with affine `(x, y) = (X/Z, Y/Z)` handle this correctly: the projective addition formula
//! works mod p^k even when Z ≡ 0 mod p (the point reduces to infinity mod p).
//!
//! # Formal group parameter from projective coordinates
//!
//! In standard projective coordinates, the formal group parameter is `t = −x/y = −X/Y`
//! (the Z factors cancel). After multiply-by-p, `v_p(Z) ≥ 1` and `v_p(t) ≥ 1`.
//!
//! # Verification step and the `k_raw` versus `k_raw / 2` candidates
//!
//! The reduction produces a quotient `k_raw = ψ(p·Q̃) / ψ(p·G̃) mod p`, which is only a
//! candidate: `k·G = Q` is checked in E(F_p) before anything is returned. When `k_raw·G ≠ Q`
//! the candidate `k_raw · 2⁻¹ mod p` is checked too.
//!
//! **The halving does not follow from the formal-group derivation.** For a lift on which
//! `p·P̃` lies in `E_1 \ E_2` (`v_p(t) = 1`) the map `P ↦ ψ(p·P̃)/p mod p` is a homomorphism
//! `E(F_p) → F_p` independent of the choice of lifted point, because changing `P̃` by a
//! kernel point `κ` changes `p·P̃` by `p·κ ∈ E_2`. The quotient is then exactly `k`, and no
//! factor 2 arises. The factor appears only on the toy fixture, and is observed to come with a
//! degenerate lift: `y² = x³ + 5` over `F_7` has `a = 0`, so its verbatim lift to Z_7 keeps
//! `j = 0` (complex multiplication by Z[ζ₃], 7 split in Q(ζ₃); this is the canonical lift,
//! on which the reduction is known to break down). Measured on this fixture, `p·P̃ ∈ E_2` for
//! every point and for every lift `b̃ = 5 + 7j`, so `ψ(p·P̃)` has valuation 2 or more; its leading
//! unit is then a second-order artefact that depends on the lift and is not additive in `P`,
//! and for `k = 2, …, 5` it equals `2k mod 7` (`k = ±1` give `±1` trivially, since `Q̃ = ±G̃`).
//! Lifting the same curve with `a ≡ 0 mod p` but `a ≠ 0` (`a = 7, 14, 21`) gives valuation 1
//! and `k_raw = k` for every `k`, with no halving. The halving is therefore an empirical
//! compensation for a degenerate lift, kept because the verification makes it safe, not a
//! property of the formal logarithm.
//!
//! In the prime-order group generated by `G` the solution of `k·G = Q` is unique modulo `p`,
//! so at most one of the two candidates can verify (they coincide only for `k_raw = 0`, which
//! never verifies for `Q ≠ ∞`). `resolve_candidate` records which one did.
//!
//! # Scale limits
//!
//! Toy scale only: p = 7, k = 8. The verification is O(1): at most 2 scalar multiplications.

